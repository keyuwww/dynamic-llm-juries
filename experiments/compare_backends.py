#!/usr/bin/env python3
"""
Jev vs CLM, side by side. Reads metrics.json written by the two experiments:

  experiments/jev_router/{jev,clm}_router_results/metrics.json   (Exp 2: certifier / router)
  experiments/jev_bff/{jev,clm}_bff_results/metrics.json         (Exp 1: correctness judge)

Usage (repo root):  uv run python experiments/compare_backends.py
Writes experiments/backend_comparison.md
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BACKENDS = ["jev", "clm"]


def load(path):
    try:
        return json.loads(Path(path).read_text())
    except FileNotFoundError:
        return None


def f(x, nd=3):
    return "–" if x is None else (str(x) if isinstance(x, int) else f"{x:.{nd}f}" if isinstance(x, float) else str(x))


def main():
    L = ["# Jev vs CLM", "", "Generated by `experiments/compare_backends.py`. '–' = not run yet.", ""]

    r = {b: load(HERE / "jev_router" / f"{b}_router_results" / "metrics.json") for b in BACKENDS}
    L += ["## Exp 2: certifier / router (question only → which models will be right?)", "",
          "| Metric | " + " | ".join(b.upper() for b in BACKENDS) + " |", "|---|" + "---|" * len(BACKENDS)]
    rows = [("Backend model", "backend_model"), ("Question-turns", "n_questions"),
            ("Certifier AUROC (yes/no P)", "auroc"), ("Certifier AUROC (choice P)", "auroc_choice_prob"),
            ("Prior baseline AUROC (model's avg accuracy)", "auroc_prior"),
            ("Brier (lower better)", "brier"), ("Brier, prior baseline", "brier_prior"),
            ("Routing acc: random model", "route_random"), ("Routing acc: best single model", "route_best_single"),
            ("Routing acc: highest yes/no P", "route_noul"), ("Routing acc: choice question", "route_choice"),
            ("Routing acc: oracle", "route_oracle"),
            ("Gap closed (yes/no)", "gap_closed_noul"), ("Gap closed (choice)", "gap_closed_choice"),
            ("'None will be right' AUROC", "none_auroc")]
    for label, k in rows:
        L.append(f"| {label} | " + " | ".join(f((r[b] or {}).get(k)) if not isinstance((r[b] or {}).get(k), list)
                                              else ", ".join(r[b][k]) for b in BACKENDS) + " |")

    j = {b: load(HERE / "jev_bff" / f"{b}_bff_results" / "metrics.json") for b in BACKENDS}
    L += ["", "## Exp 1: correctness judge (is this answer correct?)", "",
          "| Metric | " + " | ".join(f"{b.upper()} {c}" for b in BACKENDS for c in ("noref", "ref")) + " |",
          "|---|" + "---|" * (2 * len(BACKENDS))]
    for label, k in [("n", "n"), ("Accuracy", "acc"), ("Cohen's κ", "kappa"), ("AUROC", "auroc"),
                     ("False-positive rate", "fpr"), ("False-negative rate", "fnr")]:
        L.append(f"| {label} | " + " | ".join(f(((j[b] or {}).get(c) or {}).get(k)) for b in BACKENDS for c in ("noref", "ref")) + " |")
    L += ["", "Reference: No Free Labels reports GPT-4o overall κ ≈ 0.69 with a human reference, ≈ 0.46 without.", ""]
    out = HERE / "backend_comparison.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
